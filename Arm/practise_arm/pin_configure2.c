#include<LPC21xx.h>
#include "delay.h"
int main()
{
	PINSEL1=0;

	while(1)
		{
		IODIR0|=((1<<0)|(1<<15)|(1<<27)|(1<<28)|(1<<29)|(1<<30));
		IODIR1|=((1<<16)|(1<<31));
		
			Delay(1000);
		IOSET0=((1<<0)|(1<<15)|(1<<27)|(1<<28)|(1<<29)|(1<<30));
		IOSET1=((1<<16)|(1<<31));
			Delay(1000);
		IOCLR0=((1<<0)|(1<<15)|(1<<27)|(1<<28)|(1<<29)|(1<<30));
		IOCLR1=((1<<16)|(1<<31));
			Delay(1000);
		IODIR0&=~((1<<0)|(1<<15)|(1<<27)|(1<<28)|(1<<29)|(1<<30));
		IODIR1&=~((1<<16)|(1<<31));
			Delay(1000);
	}
}
